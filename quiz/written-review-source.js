function buildReviewGroups() {
  const used = new Set();
  const groups = coverage.blocks.map((block) => ({
    file: block.file,
    category: "self-check",
    title: "추가 설명·자가 점검",
    rows: block.items.map((item) => {
      const row = answers[item.sourceId];
      if (!row || used.has(item.sourceId))
        throw new Error(`자가 점검 원본 누락·중복: ${item.sourceId}`);
      used.add(item.sourceId);
      return [item.sourceId, ...row];
    }),
  }));
  if (used.size !== Object.keys(answers).length)
    throw new Error("자가 점검 선택지에 연결되지 않은 문항이 있습니다.");
  return groups;
}

module.exports = { buildReviewGroups, coverage };
